
"""
deepeval_groq_model.py

Purpose:
    Connect DeepEval to a Groq-hosted LLM so DeepEval can use it
    as an LLM judge when evaluating the RAG retrieval component.

How it works:
    1. DeepEval sends an evaluation prompt to this class.
    2. This class sends the prompt to Groq using LangChain's ChatGroq.
    3. Groq generates a response.
    4. This class returns the response to DeepEval for scoring.

Example model:
    openai/gpt-oss-120b

Environment variable required:
    GROQ_API_KEY

Important:
    This class provides the model integration only.
    Evaluation metrics, thresholds, and test cases are defined elsewhere.
"""

import os
from typing import Optional, Type

from deepeval.models import DeepEvalBaseLLM
from langchain_groq import ChatGroq
from pydantic import BaseModel


class DeepEvalGroqModel(DeepEvalBaseLLM):
    """
    Adapt a LangChain ChatGroq model to DeepEval's custom LLM interface.

    DeepEval uses this class to generate the judgments needed by metrics
    such as contextual precision and contextual recall.
    """

    def __init__(
        self,
        model_name: str = "openai/gpt-oss-120b",
        temperature: float = 0,
    ) -> None:
        """
        Initialize the Groq model.

        Args:
            model_name:
                The model identifier accepted by Groq.

            temperature:
                Controls response randomness. A value of 0 is suitable
                for evaluation because consistent judgments are desirable.

        Raises:
            ValueError:
                If GROQ_API_KEY is not configured.
        """

        # Read the API key from the environment.
        # Never hardcode or print the secret API key.
        api_key = os.getenv("GROQ_API_KEY")

        if not api_key:
            raise ValueError(
                "GROQ_API_KEY is not configured. "
                "Set it in your environment or project .env configuration."
            )

        # Store the model name so reports can identify the judge.
        self.model_name = model_name

        # Create the LangChain chat model that sends prompts to Groq.
        self.model = ChatGroq(
            model=model_name,
            temperature=temperature,
            api_key=api_key,
        )

    def load_model(self) -> ChatGroq:
        """
        Return the initialized LangChain model.

        Keeping this in a separate method makes the model easy to access
        from both synchronous and asynchronous generation methods.
        """
        return self.model

    def generate(
        self,
        prompt: str,
        schema: Optional[Type[BaseModel]] = None,
    ):
        """
        Generate a response synchronously.

        Args:
            prompt:
                The evaluation instructions generated by DeepEval.

            schema:
                An optional Pydantic model defining the expected structure
                of the response. When supplied, structured output is used.

        Returns:
            A string for ordinary responses, or a Pydantic model instance
            for structured responses.

        Note:
            Return the response itself, not a (response, token_count) tuple.
        """

        llm = self.load_model()

        # Some DeepEval metrics request structured output, such as a
        # response containing specific fields for an evaluation judgment.
        if schema is not None:
            if isinstance(schema, type) and issubclass(schema, BaseModel):
                structured_llm = llm.with_structured_output(schema, method="json_mode")

                # Groq generates data matching the supplied Pydantic schema.
                return structured_llm.invoke(prompt)

        # Ordinary text generation: send the prompt to Groq.
        response = llm.invoke(prompt)

        # LangChain returns an AIMessage; DeepEval needs its text content.
        return response.content

    async def a_generate(
        self,
        prompt: str,
        schema: Optional[Type[BaseModel]] = None,
    ):
        """
        Generate a response asynchronously.

        This method provides the same functionality as generate(), but
        uses asynchronous LangChain calls. It allows DeepEval to use
        async evaluation workflows without blocking on each model call.

        Args:
            prompt:
                The evaluation prompt generated by DeepEval.

            schema:
                An optional Pydantic model for structured output.

        Returns:
            A string for ordinary responses, or a Pydantic model instance
            for structured responses.
        """

        llm = self.load_model()

        # Handle structured output in asynchronous mode.
        if schema is not None:
            if isinstance(schema, type) and issubclass(schema, BaseModel):
                structured_llm = llm.with_structured_output(schema, method="json_mode")

                # Wait for Groq to return a structured response.
                return await structured_llm.ainvoke(prompt)

        # Handle ordinary text generation asynchronously.
        response = await llm.ainvoke(prompt)

        # Return the generated text rather than the AIMessage wrapper.
        return response.content

    def get_model_name(self) -> str:
        """
        Return the model identifier.

        DeepEval can use this name when identifying the judge model
        in evaluation output and reports.
        """
        return self.model_name
