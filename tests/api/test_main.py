# TEST 11: SUCCESSFUL CHAT AND CONVERSATION HISTORY
# ============================================================

def test_chat_success_saves_answer_and_history(monkeypatch):
    """
    Verify that a valid chat request:
        1. Loads the retriever.
        2. Sends the question and previous history to RAG.
        3. Returns the generated answer.
        4. Saves the new question and answer in session history.
    """

    session_id = "test-session-123"

    # Prepare an existing conversation for this session.
    main.SESSIONS[session_id] = [
        {"role": "user", "content": "What is this document about?"},
        {"role": "assistant", "content": "It is about software testing."},
    ]

    # Fake RAG class: simulates retrieval and answer generation.
    class FakeConversationalRAG:
        def __init__(self, session_id):
            assert session_id == "test-session-123"

        def load_retriever_from_faiss(
            self,
            index_path,
            search_type,
            fetch_k,
            lambda_mult,
        ):
            # Verify that the API uses the expected retrieval settings.
            assert index_path == f"faiss_index/{session_id}"
            assert search_type == "mmr"
            assert fetch_k == 20
            assert lambda_mult == 0.5

        def invoke(self, message, chat_history):
            # Confirm that the user's current question reaches RAG.
            assert message == "Summarize the document"

            # Confirm that the earlier conversation was passed to RAG.
            assert len(chat_history) == 2
            assert chat_history[0].content == "What is this document about?"
            assert chat_history[1].content == "It is about software testing."

            # Return a simulated answer instead of calling a real LLM.
            return "The document explains software testing."

    # Replace the real RAG class with our fake class for this test.
    monkeypatch.setattr(
        main,
        "ConversationalRAG",
        FakeConversationalRAG,
    )

    # Send a valid chat request.
    response = client.post(
        "/chat",
        json={
            "session_id": session_id,
            "message": "Summarize the document",
        },
    )

    # Verify the successful HTTP response and answer.
    assert response.status_code == 200
    assert response.json() == {
        "answer": "The document explains software testing."
    }

    # Verify that the new user message was saved.
    history = main.SESSIONS[session_id]
    assert history[-2] == {
        "role": "user",
        "content": "Summarize the document",
    }

    # Verify that the generated answer was saved.
    assert history[-1] == {
        "role": "assistant",
        "content": "The document explains software testing.",
    }



