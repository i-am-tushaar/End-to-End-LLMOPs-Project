"""
models.py

Purpose:
--------
This file contains all the Pydantic models used by the application.

Why do we need this file?
-------------------------
Instead of passing dictionaries everywhere, we define schemas
(models) that validate incoming and outgoing data.

Benefits:
- Automatic data validation
- Type checking
- Better IDE support
- Automatic FastAPI documentation
- Cleaner and maintainable code
"""

# ============================================================
# Imports
# ============================================================

# BaseModel is the parent class for all Pydantic models.
# Every request/response schema will inherit from it.
from pydantic import BaseModel, Field

# Annotated lets us combine a datatype with validation rules.
from typing import Annotated

# Enum is used to create fixed constant values.
from enum import Enum


# ============================================================
# Chat Answer Model
# ============================================================

class ChatAnswer(BaseModel):
    """
    Represents the final answer generated by the LLM.

    Why this model?
    ---------------
    Instead of returning any random string,
    this model ensures:

    - answer cannot be empty
    - answer length cannot exceed 4096 characters

    Example
    -------
    Valid:

    {
        "answer": "Paris is the capital of France."
    }

    Invalid:

    {
        "answer": ""
    }

    because minimum length is 1.
    """

    answer: Annotated[
        str,
        Field(
            min_length=1,
            max_length=4096
        )
    ]


# ============================================================
# Prompt Type Enum
# ============================================================

class PromptType(str, Enum):
    """
    Stores all prompt names used in the application.

    Why Enum?
    ---------
    Prevents typing mistakes.

    Instead of writing:

        "context_qa"

    everywhere in the project,
    we write:

        PromptType.CONTEXT_QA

    Benefits
    --------
    ✔ Auto completion
    ✔ No spelling mistakes
    ✔ Easy maintenance
    """

    CONTEXTUALIZE_QUESTION = "contextualize_question"

    CONTEXT_QA = "context_qa"


# ============================================================
# Upload Response Model
# ============================================================

class UploadResponse(BaseModel):
    """
    Response returned after document upload.

    Example
    -------

    {
        "session_id": "abc123",
        "indexed": true,
        "message": "Document uploaded successfully."
    }

    Attributes
    ----------
    session_id
        Unique chat/document session.

    indexed
        Indicates whether the document
        was successfully stored in the vector database.

    message
        Optional status message.
    """

    session_id: str

    indexed: bool

    message: str | None = None


# ============================================================
# Chat Request Model
# ============================================================

class ChatRequest(BaseModel):
    """
    Incoming request sent by the user.

    Example
    -------

    {
        "session_id": "abc123",
        "message": "Summarize the uploaded PDF."
    }

    Attributes
    ----------
    session_id
        Identifies which uploaded document
        should be searched.

    message
        User's question.
    """

    session_id: str

    message: str


# ============================================================
# Chat Response Model
# ============================================================

class ChatResponse(BaseModel):
    """
    Final response returned to the frontend.

    Example
    -------

    {
        "answer": "The document discusses RAG architecture."
    }
    """

    answer: str



