# TEST 5: SUCCESSFUL DOCUMENT UPLOAD
# ============================================================

def test_upload_successfully_creates_session(monkeypatch):
    """
    Verify that uploading a document creates a chat session.

    We mock ChatIngestor to avoid running the real ingestion pipeline.
    """

    # Create a fake ingestion class for this test.
    class FakeChatIngestor:
        def __init__(self, use_session_dirs):
            # Simulate the session ID normally generated by ingestion.
            self.session_id = "test-session-123"

            # Verify that session-specific directories are enabled.
            assert use_session_dirs is True

        def built_retriver(
            self,
            uploaded_files,
            search_type,
            fetch_k,
            lambda_mult,
        ):
            # Verify that the API passes the expected retrieval settings.
            assert len(uploaded_files) == 1
            assert search_type == "mmr"
            assert fetch_k == 20
            assert lambda_mult == 0.5

            # Verify that the uploaded file can be read.
            assert uploaded_files[0].name == "notes.txt"
            assert uploaded_files[0].getbuffer() == b"Sample document"

    # Replace the real class with our fake class during this test.
    monkeypatch.setattr(
        main,
        "ChatIngestor",
        FakeChatIngestor,
    )

    # Send a file to the upload endpoint.
    response = client.post(
        "/upload",
        files=[
            (
                "files",
                ("notes.txt", b"Sample document", "text/plain"),
            )
        ],
    )

    # Verify the API response.
    assert response.status_code == 200

    data = response.json()

    assert data["session_id"] == "test-session-123"
    assert data["indexed"] is True
    assert data["message"] == "Indexing complete with MMR"

    # Verify that the API initialized an empty chat history.
    assert main.SESSIONS["test-session-123"] == []



